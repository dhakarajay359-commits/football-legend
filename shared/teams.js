function makePlayer(id, name, number, role, ovr, stats) {
  return {
    id,
    name,
    number,
    role,
    ovr,
    pace: stats.pace ?? ovr,
    shooting: stats.shooting ?? ovr,
    passing: stats.passing ?? ovr,
    dribbling: stats.dribbling ?? ovr,
    defending: stats.defending ?? ovr,
    physical: stats.physical ?? ovr,
    gk: stats.gk ?? (role === 'GK' ? ovr : 35),
    skinTone: stats.skin ?? '#d8a47f',
    hairColor: stats.hair ?? '#1f1b18'
  };
}

function buildSquad(prefix, baseOvr, stars) {
  const s = (idx, defName, num, role, boost = 0, overrides = {}) => {
    const st = stars[idx] || {};
    const ovr = Math.min(96, Math.max(66, (st.ovr ?? baseOvr) + boost));
    const isGK = role === 'GK';
    const isDef = ['CB', 'LB', 'RB', 'LWB', 'RWB'].includes(role);
    const isFwd = ['ST', 'LW', 'RW', 'CAM'].includes(role);
    return makePlayer(`${prefix}_${num}`, st.name ?? defName, num, role, ovr, {
      pace: st.pace ?? (isGK ? 54 : isFwd ? ovr + 3 : isDef ? ovr - 2 : ovr),
      shooting: st.shooting ?? (isGK ? 30 : isFwd ? ovr + 2 : isDef ? ovr - 16 : ovr - 4),
      passing: st.passing ?? (isGK ? 68 : isDef ? ovr - 5 : ovr + 1),
      dribbling: st.dribbling ?? (isGK ? 45 : isFwd ? ovr + 2 : isDef ? ovr - 8 : ovr),
      defending: st.defending ?? (isGK ? 42 : isDef ? ovr + 3 : isFwd ? 44 : ovr - 8),
      physical: st.physical ?? (isDef ? ovr + 2 : ovr - 2),
      gk: isGK ? ovr + 2 : 30,
      skin: st.skin ?? ['#f1c29b', '#d8a47f', '#b67852', '#6f422b', '#e5b88f'][idx % 5],
      hair: st.hair ?? ['#1a1614', '#3b281d', '#6e4c2a', '#d2a64c', '#111111'][idx % 5],
      ...overrides
    });
  };

  return [
    s(0, 'A. Valdes', 1, 'GK', 1),
    s(1, 'L. Mendes', 3, 'LB', -1),
    s(2, 'R. Silva', 4, 'CB', 0),
    s(3, 'K. Becker', 5, 'CB', 1),
    s(4, 'T. Vance', 2, 'RB', -1),
    s(5, 'D. Kovac', 6, 'CDM', 0),
    s(6, 'M. Veron', 8, 'CM', 1),
    s(7, 'J. Sterling', 10, 'CM', 2),
    s(8, 'V. Rocha', 11, 'LW', 2),
    s(9, 'K. Moreau', 9, 'ST', 3),
    s(10, 'B. Corvo', 7, 'RW', 2),
    s(11, 'N. Costa', 13, 'GK', -4),
    s(12, 'P. Torres', 15, 'CB', -3),
    s(13, 'C. Ruiz', 14, 'CM', -2),
    s(14, 'S. Diaby', 17, 'LW', -2),
    s(15, 'A. Morano', 19, 'ST', -2)
  ];
}

